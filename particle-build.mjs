const profileSection=`<section><h2>SIDE PROFILE</h2><label class=\"upload\">SIDE PHOTO<input id=\"profileFiles\" type=\"file\" accept=\"image/*\"></label><select id=\"profileChoice\"><option value=\"-1\">NO PROFILE LOADED</option></select><canvas id=\"profileCanvas\"></canvas><div id=\"profileStatus\" class=\"note\">Load a side photograph to begin.</div></section>`;
const autoAlign=`<button id=\"autoAlign\">AUTOMATIC ALIGNMENT</button>`;
html=html.replace('<button id=\"measure\">PICK BASE + TIP</button>',`<button id=\"measure\">PICK BASE + TIP</button>${autoAlign}`);
html=html.replace('<section><h2>02 / SHAPE</h2>',`${profileSection}<section><h2>02 / SHAPE</h2>`);
const injected=['profile-core.js','boundary.js','automation.js','transition.js','surfaces.js','profile-geometry.js','profile-editor.js','interface.js','organic-interface.js','particle-buttons.js'].map(file=>fs.readFileSync(file,'utf8')).join('\n');
