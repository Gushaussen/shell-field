import './organic-build.mjs';
import fs from 'node:fs';
let html=fs.readFileSync('public/index.html','utf8');
const marker='</script></body>';
if(!html.includes(marker))throw Error('Grain interface insertion point missing');
let buttons=fs.readFileSync('grain-buttons.js','utf8');
buttons=buttons.replace('inset:-4px -7px','inset:0');
buttons=buttons.replaceAll('ellipse 70% 100% at 50% 60%','ellipse 50% 50% at 50% 50%');
buttons=buttons.replace('var(--b,#0648ff) 48%,color-mix(in srgb,var(--b,#0648ff) 92%,transparent) 62%,color-mix(in srgb,var(--b,#0648ff) 42%,transparent) 80%','var(--b,#0648ff) 58%,color-mix(in srgb,var(--b,#0648ff) 45%,transparent) 76%,color-mix(in srgb,var(--b,#0648ff) 10%,transparent) 90%');
buttons=buttons.replaceAll('#000 48%,#000e 62%,#0006 80%','#000 58%,#0007 76%,#0002 90%');
html=html.replace(marker,buttons+'\n'+marker);
fs.writeFileSync('public/index.html',html);
