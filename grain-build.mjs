import './organic-build.mjs';
import fs from 'node:fs';
let html=fs.readFileSync('public/index.html','utf8');
const marker='</script></body>';
if(!html.includes(marker))throw Error('Grain interface insertion point missing');
let buttons=fs.readFileSync('grain-buttons.js','utf8');
buttons=buttons.replaceAll('ellipse 50% 50% at 50% 50%','ellipse 28% 32% at 50% 52%');
buttons=buttons.replace('var(--b,#0648ff) 58%,color-mix(in srgb,var(--b,#0648ff) 45%,transparent) 76%,color-mix(in srgb,var(--b,#0648ff) 10%,transparent) 90%','var(--b,#0648ff) 30%,color-mix(in srgb,var(--b,#0648ff) 55%,transparent) 52%,color-mix(in srgb,var(--b,#0648ff) 12%,transparent) 74%,transparent 88%');
buttons=buttons.replaceAll('#000 58%,#0007 76%,#0002 90%','#000 30%,#0008 52%,#0003 74%,transparent 88%');
buttons=buttons.replaceAll('opacity:.65','opacity:.85');
buttons=buttons.replace('mix-blend-mode:soft-light','mix-blend-mode:overlay');
html=html.replace(marker,buttons+'\n'+marker);
fs.writeFileSync('public/index.html',html);
